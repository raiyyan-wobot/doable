// Generates the design tokens that can't be written by hand precisely:
//
//   src/styles/generated/motion.css   M3 spring motion as CSS `linear()` easings
//   src/styles/generated/color.css    fallback M3 color scheme (light + dark)
//
// Run with `pnpm tokens` after changing a constant below. Output is committed.
// (`pnpm tokens` preloads scripts/resolve-js-extension.mjs; see that file.)
//
// Sources: androidx Compose Material 3 tokens
//   tokens/ExpressiveMotionTokens.kt, tokens/StandardMotionTokens.kt
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { BASELINE_SEED, DEFAULT_COLOR_STYLE, createSchemeVars } from "../src/theme/scheme.ts";

const OUT_DIR = join(dirname(fileURLToPath(import.meta.url)), "../src/styles/generated");

// ---------------------------------------------------------------------------
// Motion: springs → linear()
// ---------------------------------------------------------------------------

/** M3 motion schemes: { damping ratio, stiffness } per token (mass = 1). */
const SPRINGS = {
  expressive: {
    "fast-spatial": { damping: 0.6, stiffness: 800 },
    "default-spatial": { damping: 0.8, stiffness: 380 },
    "slow-spatial": { damping: 0.8, stiffness: 200 },
    "fast-effects": { damping: 1, stiffness: 3800 },
    "default-effects": { damping: 1, stiffness: 1600 },
    "slow-effects": { damping: 1, stiffness: 800 },
  },
  standard: {
    "fast-spatial": { damping: 0.9, stiffness: 1400 },
    "default-spatial": { damping: 0.9, stiffness: 700 },
    "slow-spatial": { damping: 0.9, stiffness: 300 },
    "fast-effects": { damping: 1, stiffness: 3800 },
    "default-effects": { damping: 1, stiffness: 1600 },
    "slow-effects": { damping: 1, stiffness: 800 },
  },
};

/** Progress (0 → 1, may overshoot) of a unit spring released from rest at time t (seconds). */
function springPosition({ damping, stiffness }, t) {
  const w0 = Math.sqrt(stiffness);
  if (damping < 1) {
    const wd = w0 * Math.sqrt(1 - damping * damping);
    const decay = Math.exp(-damping * w0 * t);
    return 1 - decay * (Math.cos(wd * t) + ((damping * w0) / wd) * Math.sin(wd * t));
  }
  // Critically damped.
  return 1 - Math.exp(-w0 * t) * (1 + w0 * t);
}

/** Time until the spring stays within 0.1% of its target (Compose's default visibility threshold). */
function settleTime(spring) {
  const dt = 0.001;
  let lastOutside = 0;
  for (let t = 0; t < 5; t += dt) {
    if (Math.abs(1 - springPosition(spring, t)) > 0.001) lastOutside = t;
  }
  return lastOutside + dt;
}

function linearEasing(spring, duration, samples = 48) {
  const points = [];
  for (let i = 0; i <= samples; i++) {
    const p = i === samples ? 1 : springPosition(spring, (duration * i) / samples);
    points.push(Number(p.toFixed(4)));
  }
  return `linear(${points.join(", ")})`;
}

function motionCss() {
  const lines = [];
  for (const [scheme, springs] of Object.entries(SPRINGS)) {
    lines.push(`  /* ${scheme} motion scheme */`);
    for (const [name, spring] of Object.entries(springs)) {
      const duration = settleTime(spring);
      const prefix = `--md-motion-${scheme}-${name}`;
      lines.push(`  ${prefix}-duration: ${Math.round(duration * 1000)}ms;`);
      lines.push(`  ${prefix}-easing: ${linearEasing(spring, duration)};`);
    }
  }
  return `/* GENERATED by scripts/generate-tokens.mjs. Do not edit by hand. */
/* M3 spring motion tokens, sampled into CSS linear() easing functions. */
:root {
${lines.join("\n")}
}
`;
}

// ---------------------------------------------------------------------------
// Color: fallback scheme for first paint / no system accent
// ---------------------------------------------------------------------------

function schemeVars(isDark) {
  return Object.entries(createSchemeVars(BASELINE_SEED, isDark, DEFAULT_COLOR_STYLE))
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");
}

function colorCss() {
  return `/* GENERATED by scripts/generate-tokens.mjs. Do not edit by hand. */
/* Fallback M3 scheme (default color style, 2025 spec, seed ${BASELINE_SEED}). The theme
   provider overrides these at runtime with the scheme built from the OS accent. */
:root {
${schemeVars(false)}
}

:root.dark {
${schemeVars(true)}
}
`;
}

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, "motion.css"), motionCss());
writeFileSync(join(OUT_DIR, "color.css"), colorCss());
console.log(`wrote motion.css and color.css to ${OUT_DIR}`);
